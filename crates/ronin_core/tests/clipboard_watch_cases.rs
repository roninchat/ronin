#[test]
fn confirm_and_dismiss_matrix() {
    for i in 0..80usize {
        let mut watch = ClipboardWatchController::new();
        watch.enable(Some(&format!("b{i}")));
        let text = format!("payload-{i}-value");
        assert_eq!(watch.observe_text(&text), ClipboardObserveOutcome::Proposed);
        if i % 2 == 0 {
            let draft = watch.confirm_pending().expect("draft");
            assert!(draft.context_block.contains(&text));
            assert!(confirmed_clipboard_attach_may_inject_into_chat_request());
            assert!(watch.pending_proposal().is_none());
        } else {
            watch.dismiss_pending();
            assert!(watch.pending_proposal().is_none());
            assert!(watch.confirm_pending().is_none());
        }
    }
}

#[test]
fn disable_after_propose_matrix() {
    for i in 0..60usize {
        let mut watch = ClipboardWatchController::new();
        watch.enable(Some("x"));
        watch.observe_text(&format!("p{i}"));
        assert!(watch.pending_proposal().is_some());
        watch.disable();
        assert!(!watch.is_enabled());
        assert!(watch.pending_proposal().is_none());
        assert_eq!(
            watch.observe_text(&format!("after-{i}")),
            ClipboardObserveOutcome::IgnoredDisabled
        );
        assert!(!ClipboardWatchPrefs::default().enabled);
    }
}
