//! Table-driven clipboard watch cases (#77).

use ronin_core::{
    clipboard_watch_proposal_may_inject_into_chat_request,
    confirmed_clipboard_attach_may_inject_into_chat_request, ClipboardObserveOutcome,
    ClipboardWatchController, ClipboardWatchPrefs,
};

struct ObserveCase {
    name: &'static str,
    enable_baseline: Option<&'static str>,
    observe: &'static str,
    expect: ClipboardObserveOutcome,
    expect_pending: bool,
}

fn run_observe(case: &ObserveCase) {
    let mut watch = ClipboardWatchController::new();
    if let Some(base) = case.enable_baseline {
        watch.enable(Some(base));
    }
    let outcome = watch.observe_text(case.observe);
    assert_eq!(outcome, case.expect, "case {}", case.name);
    assert_eq!(
        watch.pending_proposal().is_some(),
        case.expect_pending,
        "case {} pending",
        case.name
    );
    assert!(!clipboard_watch_proposal_may_inject_into_chat_request());
}

