#[test]
fn deepen_options_carries_ui_browse_filter() {
    let temp = TempDir::new().unwrap();
    let root = temp.path().join("p");
    std::fs::create_dir_all(root.join("src")).unwrap();
    for i in 0..30 {
        std::fs::write(root.join("src").join(format!("a{i}.rs")), "x").unwrap();
        std::fs::write(root.join("src").join(format!("b{i}.rs")), "y").unwrap();
    }
    let listing = list_folder_entries_with_options(
        &root,
        None,
        temp.path(),
        &FolderListPolicy::default(),
        &FolderListOptions {
            max_depth: 2,
            max_entries: 10,
            browse_filter: None,
        },
    )
    .unwrap();
    let mut state = FolderAttachState::from_listing(listing);
    state.set_browse_filter("a1");
    let opts = state.deepen_options();
    assert_eq!(opts.browse_filter.as_deref(), Some("a1"));
    let deeper = list_folder_entries_with_options(
        &root,
        None,
        temp.path(),
        &FolderListPolicy::default(),
        &opts,
    )
    .unwrap();
    assert!(deeper
        .entries
        .iter()
        .all(|e| e.relative_path.contains("a1")));
}

