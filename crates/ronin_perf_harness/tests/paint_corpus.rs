#[test]
fn paint_corpus_plain_messages_produce_spans() {
    for (i, msg) in PLAIN.iter().enumerate() {
        let t = measure_chat_paint(&[(*msg).to_string()]);
        assert!(!t.spans.is_empty(), "plain {i}");
        assert_eq!(t.spans[0].name, "markdown.parse");
        let blocks = parse_markdown_blocks(msg);
        assert!(!blocks.is_empty() || msg.is_empty(), "blocks {i}");
        let _ = (t.parse, t.render, t.wall);
    }
}

#[test]
fn paint_corpus_fenced_messages_exercise_render_path() {
    for (i, msg) in FENCED.iter().enumerate() {
        let t = measure_chat_paint(&[(*msg).to_string()]);
        assert_eq!(t.spans.len(), 2, "fenced {i}");
        assert!(!parse_markdown_blocks(msg).is_empty(), "fenced blocks {i}");
    }
}

