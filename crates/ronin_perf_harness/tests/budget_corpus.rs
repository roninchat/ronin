fn budget_corpus_judge_timings_matrix() {
    for c in CASES {
        let j = judge_timings(
            c.name,
            &timing(c.obs_parse, c.obs_render, c.obs_wall),
            &timing(c.base_parse, c.base_render, c.base_wall),
            &rules(c.max_reg, c.parse_c, c.render_c, c.wall_c),
        );
        assert_eq!(
            j.passed, c.expect_pass,
            "{} failures={:?}",
            c.name, j.failures
        );
        assert_eq!(j.scenario, c.name);
        assert!(!j.hotspots.is_empty(), "{}", c.name);
        if let Some(needle) = c.must_contain {
            assert!(
                j.failures.iter().any(|f| f.contains(needle)),
                "{} => {:?}",
                c.name,
                j.failures
            );
        }
    }
}
