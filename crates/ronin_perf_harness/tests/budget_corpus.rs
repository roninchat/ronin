#![allow(clippy::too_many_lines)]

use ronin_perf_harness::{judge_timings, BudgetRules, PaintTiming, SpanTiming};
use std::time::Duration;

fn rules(max_reg: f64, parse_c: u64, render_c: u64, wall_c: u64) -> BudgetRules {
    BudgetRules {
        max_regression_ratio: max_reg,
        parse_ceiling: Duration::from_millis(parse_c),
        render_ceiling: Duration::from_millis(render_c),
        wall_ceiling: Duration::from_millis(wall_c),
    }
}

fn timing(parse: u64, render: u64, wall: u64) -> PaintTiming {
    PaintTiming {
        parse: Duration::from_millis(parse),
        render: Duration::from_millis(render),
        wall: Duration::from_millis(wall),
        spans: vec![
            SpanTiming {
                name: "markdown.parse".into(),
                duration: Duration::from_millis(parse),
            },
            SpanTiming {
                name: "chat.render".into(),
                duration: Duration::from_millis(render),
            },
        ],
    }
}

